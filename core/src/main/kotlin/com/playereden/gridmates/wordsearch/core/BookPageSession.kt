package com.playereden.gridmates.wordsearch.core

/**
 * WS-11D2A — in-progress pages are separate from Free Play, Daily and the
 * committed BookProgressCodec v1 file. Only published, exact-hash-matching
 * V2/V3 board metadata may create a session; V4 laboratory boards are blocked.
 *
 * A fully found page is deliberately retained as a recoverable session until
 * the separate completion journal has been committed. This supports a safe
 * two-step commit without erasing progress if the application stops between
 * the two AtomicFile writes.
 */
data class BookPageSession(
    val bookId: String,
    val pageId: String,
    val puzzleId: String,
    val boardSha256: String,
    val foundIds: Set<String> = emptySet(),
    val hints: Map<String, Int> = emptyMap(),
    val elapsedSeconds: Long = 0L
)

data class BookPageSessionJournal(
    val sessions: List<BookPageSession> = emptyList()
)

object BookPageSessionRules {
    const val MAX_SESSIONS = 128
    private const val MAX_ELAPSED_SECONDS = 365L * 24 * 60 * 60

    private val puzzleCache = object : LinkedHashMap<String, WordSearchPuzzle>(32, 0.75f, true) {
        override fun removeEldestEntry(
            eldest: MutableMap.MutableEntry<String, WordSearchPuzzle>
        ): Boolean = size > 32
    }

    /**
     * Can only reconstruct a page from its registered generator version,
     * exact theme/challenge/seed, and SHA-256 of every row/answer path.
     * Nothing is generated by "theme" alone; no fake or preview puzzle IDs.
     */
    @Synchronized
    fun puzzle(catalog: BookCatalog, bookId: String, pageId: String): WordSearchPuzzle {
        val book = requireNotNull(catalog.book(bookId)) { "Book not in published catalog" }
        val page = requireNotNull(catalog.page(bookId, pageId)) { "Page not in published catalog" }
        val result = puzzleCache[page.puzzleId] ?: when (page.generatorVersion) {
            WordSearchGeneratorV2.CONTENT_VERSION -> {
                require(page.boardSize in PuzzleBoardSize.bookPresets) {
                    "Unsupported V2 book size"
                }
                require(page.puzzleId == WordSearchGeneratorV2.puzzleId(
                    book.theme, page.boardSize, page.challenge, page.seed
                )) { "Book page does not match its V2 recipe" }
                WordSearchGeneratorV2.generate(
                    book.theme, page.boardSize, page.challenge, page.seed
                )
            }
            WordSearchGeneratorV3.CONTENT_VERSION -> {
                require(page.boardSize in PuzzleBoardSize.largePresets) {
                    "Unsupported V3 book size"
                }
                require(page.puzzleId == WordSearchGeneratorV3.puzzleId(
                    book.theme, page.boardSize, page.challenge, page.seed
                )) { "Book page does not match its V3 recipe" }
                WordSearchGeneratorV3.generate(
                    book.theme, page.boardSize, page.challenge, page.seed
                )
            }
            else -> throw IllegalArgumentException(
                "Unsupported book generator version; do not route V4 preview or new content"
            )
        }
        require(catalog.matchesPublishedPuzzle(bookId, pageId, result)) {
            "Book page content differs from frozen published manifest"
        }
        puzzleCache[page.puzzleId] = result
        return result
    }

    /** No invalid IDs are dropped or normalized on load. Fail closed. */
    fun validate(catalog: BookCatalog, journal: BookPageSessionJournal) {
        require(journal.sessions.size <= MAX_SESSIONS) {
            "Too many in-progress book pages; explicitly finish pages before opening more"
        }
        val keys = HashSet<String>()
        for (session in journal.sessions) {
            require(keys.add(session.bookId + ":" + session.pageId)) {
                "Duplicate saved book session"
            }
            val board = puzzle(catalog, session.bookId, session.pageId)
            require(session.puzzleId == board.id &&
                session.boardSha256 == BookBoardDigest.sha256(board)) {
                "Saved book session no longer matches its published page"
            }
            val targets = board.targets.map { it.id }.toSet()
            require(session.foundIds.all { it in targets } &&
                session.hints.all { (id, level) -> id in targets && level in 1..3 } &&
                session.elapsedSeconds in 0L..MAX_ELAPSED_SECONDS) {
                "Invalid found words, hint steps or elapsed time"
            }
            // Do not reject completed pages: crash after session commit but
            // before completion-journal commit must be recoverable.
        }
    }

    fun session(journal: BookPageSessionJournal, bookId: String, pageId: String):
        BookPageSession? = journal.sessions.firstOrNull {
            it.bookId == bookId && it.pageId == pageId
        }

    fun open(
        catalog: BookCatalog,
        journal: BookPageSessionJournal,
        bookId: String,
        pageId: String
    ): BookPageSessionJournal {
        validate(catalog, journal)
        if (session(journal, bookId, pageId) != null) return journal
        require(journal.sessions.size < MAX_SESSIONS) {
            "All book session slots are in use"
        }
        val board = puzzle(catalog, bookId, pageId)
        val fresh = BookPageSession(
            bookId = bookId, pageId = pageId, puzzleId = board.id,
            boardSha256 = BookBoardDigest.sha256(board)
        )
        return journal.copy(sessions = journal.sessions + fresh).also {
            validate(catalog, it)
        }
    }

    /** All finds go through the original tested word-path rules. */
    fun find(
        catalog: BookCatalog,
        journal: BookPageSessionJournal,
        bookId: String,
        pageId: String,
        start: GridPoint,
        end: GridPoint
    ): Pair<BookPageSessionJournal, WordClaim> {
        validate(catalog, journal)
        val old = requireNotNull(session(journal, bookId, pageId)) {
            "Open a published book page before playing"
        }
        val board = puzzle(catalog, bookId, pageId)
        val claim = WordSearchRules.claim(board, old.foundIds, start, end)
        if (claim.status != ClaimStatus.FOUND) return journal to claim
        val changed = old.copy(foundIds = old.foundIds + requireNotNull(claim.target).id)
        return replace(catalog, journal, changed) to claim
    }

    fun tick(
        catalog: BookCatalog, journal: BookPageSessionJournal,
        bookId: String, pageId: String, seconds: Long = 1L
    ): BookPageSessionJournal {
        require(seconds in 1L..60L) { "Foreground tick must be bounded" }
        validate(catalog, journal)
        val old = requireNotNull(session(journal, bookId, pageId)) { "No active page" }
        if (complete(catalog, old)) return journal
        return replace(catalog, journal, old.copy(
            elapsedSeconds = (old.elapsedSeconds + seconds).coerceAtMost(MAX_ELAPSED_SECONDS)
        ))
    }

    /**
     * Three progressive clues *per unfound word*. Prior experimental UI
     * exhausted all hints on a 20×20 page after four taps even when 24 words
     * remained. There is no arbitrary page-wide quota now: at most 3 × the
     * published target count can ever be persisted, preserving GMWS v1 bounds.
     * Hints still never claim words or alter Solo.
     */
    fun hint(
        catalog: BookCatalog, journal: BookPageSessionJournal,
        bookId: String, pageId: String
    ): Pair<BookPageSessionJournal, WordTarget?> {
        validate(catalog, journal)
        val old = requireNotNull(session(journal, bookId, pageId)) { "No active page" }
        val board = puzzle(catalog, bookId, pageId)
        if (WordSearchRules.complete(board, old.foundIds)) return journal to null
        val chosen = board.targets.firstOrNull {
            it.id !in old.foundIds && (old.hints[it.id] ?: 0) in 1..2
        } ?: board.targets.firstOrNull {
            it.id !in old.foundIds && (old.hints[it.id] ?: 0) == 0
        } ?: return journal to null // Every remaining word already has its full three hints.
        val count = old.hints[chosen.id] ?: 0
        val changed = old.copy(hints = old.hints + (chosen.id to count + 1))
        return replace(catalog, journal, changed) to chosen
    }

    fun complete(catalog: BookCatalog, session: BookPageSession): Boolean {
        val board = puzzle(catalog, session.bookId, session.pageId)
        return WordSearchRules.complete(board, session.foundIds)
    }

    /** Promote only after all real words were found on the exact frozen board. */
    fun verifiedCompletion(
        catalog: BookCatalog,
        journal: BookPageSessionJournal,
        progress: BookLibraryProgress,
        bookId: String, pageId: String
    ): BookLibraryProgress {
        validate(catalog, journal)
        val saved = requireNotNull(session(journal, bookId, pageId)) {
            "Cannot award completion for a missing session"
        }
        val board = puzzle(catalog, bookId, pageId)
        require(WordSearchRules.complete(board, saved.foundIds)) {
            "The page is not solved"
        }
        return BookProgressRules.recordVerifiedCompletion(
            catalog, progress, bookId, pageId, board, saved.foundIds
        )
    }

    /**
     * Idempotent cleanup AFTER the completion file is durable. Reject removing
     * an unfinished page or a finished page without an award record.
     */
    fun clearCommitted(
        catalog: BookCatalog,
        journal: BookPageSessionJournal,
        progress: BookLibraryProgress,
        bookId: String, pageId: String
    ): BookPageSessionJournal {
        validate(catalog, journal)
        BookProgressRules.validate(catalog, progress)
        val old = session(journal, bookId, pageId) ?: return journal
        require(complete(catalog, old) &&
            pageId in progress.volumes[bookId]?.completedPageIds.orEmpty()) {
            "Do not delete uncommitted page progress"
        }
        return journal.copy(
            sessions = journal.sessions.filterNot {
                it.bookId == bookId && it.pageId == pageId
            }
        )
    }

    private fun replace(
        catalog: BookCatalog, journal: BookPageSessionJournal,
        changed: BookPageSession
    ): BookPageSessionJournal {
        val updated = journal.copy(sessions = journal.sessions.map {
            if (it.bookId == changed.bookId && it.pageId == changed.pageId)
                changed else it
        })
        validate(catalog, updated)
        return updated
    }
}
