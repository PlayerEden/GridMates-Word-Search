#!/usr/bin/env python3
"""WS-12F — PNG contact sheets of actual vector-source art for easy phone review.

Optional build-only dependencies (not bundled in Android):
    pip install Pillow==11.3.0 CairoSVG==2.8.2

The *image content* is rasterized from the exact SVGs generated by our existing
deterministic art pipeline, not generated independently per theme by an LLM.
Words, button labels and progress below are only review-sheet UI simulation.
"""
import argparse
from io import BytesIO
from pathlib import Path

import cairosvg
from PIL import Image, ImageDraw, ImageFont

CREAM = "#F4F3EB"
PAPER = "#FFFDF8"
FOREST = "#214F3F"
INK = "#263D36"
MUTED = "#55665C"
RULE = "#DFE0D6"
GOLD = "#8A6729"
FONT_SANS = "/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf"
FONT_SERIF = "/usr/share/fonts/truetype/dejavu/DejaVuSerif.ttf"
THEMES = ["woodland", "space", "garden"]


def font(path, size):
    try:
        return ImageFont.truetype(path, size)
    except OSError:
        return ImageFont.load_default()


def asset(root, kind, theme, w, h):
    path = root / kind / (theme + ".svg")
    if not path.is_file():
        raise ValueError("Missing review SVG: " + str(path))
    rendered = cairosvg.svg2png(url=str(path), output_width=w, output_height=h)
    return Image.open(BytesIO(rendered)).convert("RGBA")


def card(sheet, root, theme, x, y, width, height, compact=False):
    draw = ImageDraw.Draw(sheet)
    draw.rounded_rectangle((x, y, x + width, y + height),
                           radius=18, fill=PAPER, outline=RULE, width=2)
    pad = 22 if not compact else 14
    scale = 1 if not compact else 0.70
    draw.text((x + pad, y + pad),
              "GRIDMATES · PUZZLE BOOK · PROTOTYPE",
              font=font(FONT_SANS, 12 if not compact else 10), fill=MUTED)
    draw.text((x + pad, y + pad + (32 if not compact else 25)),
              theme.title(),
              font=font(FONT_SERIF, 32 if not compact else 25), fill=FOREST)
    draw.text((x + pad, y + pad + (83 if not compact else 62)),
              "Volume I · visual family",
              font=font(FONT_SANS, 15 if not compact else 12), fill=MUTED)
    cover_w, cover_h = (270, 360) if not compact else (142, 190)
    spine_w, spine_h = (46, 330) if not compact else (28, 183)
    cover_x = x + pad
    top = y + (139 if not compact else 110)
    sheet.alpha_composite(asset(root, "books", theme, cover_w, cover_h),
                          (cover_x, top))
    sheet.alpha_composite(asset(root, "spines", theme, spine_w, spine_h),
                          (cover_x + cover_w + 12, top + (18 if not compact else 4)))
    icon_size = 70 if not compact else 55
    icon_x = cover_x + cover_w + spine_w + 27
    names = [("emblems", "Emblem"), ("chapters", "Chapter"),
             ("bookmarks", "Bookmark"), ("seals", "Seal")]
    for index, (kind, label) in enumerate(names):
        iy = top + index * (91 if not compact else 60)
        iw, ih = (icon_size, icon_size) if kind != "bookmarks" else (
            int(icon_size * 0.55), icon_size)
        sheet.alpha_composite(asset(root, kind, theme, iw, ih),
                              (icon_x, iy))
        draw.text((icon_x + (75 if not compact else 63), iy + icon_size // 2 - 7),
                  label, font=font(FONT_SANS, 14 if not compact else 11),
                  fill=MUTED)
    bottom = y + height - (94 if not compact else 68)
    draw.line((x + pad, bottom, x + width - pad, bottom),
              fill=RULE, width=2)
    draw.text((x + pad, bottom + 13),
              theme.title() + " Volume I",
              font=font(FONT_SERIF, 17 if not compact else 14), fill=INK)
    draw.text((x + pad, bottom + (46 if not compact else 39)),
              "Native titles · Offline art · Not approved",
              font=font(FONT_SANS, 11 if not compact else 10), fill=MUTED)


def render(root, output):
    root = Path(root)
    output = Path(output)
    output.mkdir(parents=True, exist_ok=True)
    sheet = Image.new("RGBA", (1940, 860), CREAM)
    draw = ImageDraw.Draw(sheet)
    draw.text((42, 22), "One little library. Three different worlds.",
              font=font(FONT_SERIF, 35), fill=FOREST)
    draw.text((45, 74),
              "WS-12F · Six-piece paperback families from one reproducible art system · PROTOTYPE",
              font=font(FONT_SANS, 16), fill=MUTED)
    for i, theme in enumerate(THEMES):
        card(sheet, root, theme, 42 + i * 635, 124, 610, 700)
    sheet.convert("RGB").save(output / "WS12F-three-book-art-contact-sheet.png",
                               optimize=True)

    # Phone-width stacked layout, approximating a 390dp book-browse screen.
    phone = Image.new("RGBA", (460, 1740), CREAM)
    pd = ImageDraw.Draw(phone)
    pd.text((18, 15), "Puzzle Books · Art Lab",
            font=font(FONT_SERIF, 28), fill=FOREST)
    pd.text((18, 54), "Unapproved · source-controlled art preview",
            font=font(FONT_SANS, 12), fill=MUTED)
    for i, theme in enumerate(THEMES):
        card(phone, root, theme, 14, 95 + i * 541, 432, 526, compact=True)
    phone.convert("RGB").save(output / "WS12F-phone-width-art-preview.png",
                               optimize=True)
    return [
        str(output / "WS12F-three-book-art-contact-sheet.png"),
        str(output / "WS12F-phone-width-art-preview.png"),
    ]


def main():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument("--input-dir", required=True)
    p.add_argument("--output-dir", required=True)
    a = p.parse_args()
    for file in render(a.input_dir, a.output_dir):
        print(file)


if __name__ == "__main__":
    main()
